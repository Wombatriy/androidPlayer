#requires -Version 5.1
<#
Build locally signed APK (-Bundle to produce Google Play AAB).
The exact Git source revision is embedded into BuildConfig and a full
corresponding-source ZIP is produced for GPL distribution alongside it.

EXAMPLES:
  .\tools\release\build-release.ps1
  .\tools\release\build-release.ps1 -Bundle

The release signing keystore stays on your computer. Never upload it.
#>
param(
    [string]$KeyStorePath = (Join-Path $HOME ".android\androidplayer-release.jks"),
    [string]$Alias = "androidplayer",
    [switch]$Bundle
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"
$root = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot "..\..")).Path
$gradlew = Join-Path $root "gradlew.bat"
$sourceScript = Join-Path $PSScriptRoot "package-corresponding-source.ps1"
$vendor = Join-Path $root "app\src\main\cpp\vendor\rubberband\single\RubberBandSingle.cpp"

if (-not (Test-Path -LiteralPath $gradlew)) { throw "Gradle wrapper not found." }
if (-not (Test-Path -LiteralPath $sourceScript)) {
    throw "Source packaging script is missing."
}
if (-not (Test-Path -LiteralPath $KeyStorePath)) {
    throw "Signing keystore missing. First run tools\release\create-keystore.ps1"
}
if (-not (Test-Path -LiteralPath $vendor)) {
    throw "Rubber Band checkout missing. Run tools\dsp\prepare-rubberband.ps1"
}

$changes = @(& git -C $root status --porcelain)
if ($LASTEXITCODE -ne 0 -or $changes.Count -gt 0) {
    throw "Release requires a clean Git worktree. Commit the source changes first."
}
$sourceRevision = (& git -C $root rev-parse HEAD).Trim()
if ($LASTEXITCODE -ne 0 -or $sourceRevision -notmatch '^[0-9a-f]{40}$') {
    throw "Could not determine the exact source revision."
}

$secret = Read-Host "Release keystore password" -AsSecureString
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secret)
try {
    $password = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
    $env:ANDROID_RELEASE_KEYSTORE = (Resolve-Path -LiteralPath $KeyStorePath).Path
    $env:ANDROID_RELEASE_STORE_PASSWORD = $password
    $env:ANDROID_RELEASE_KEY_ALIAS = $Alias
    # The PKCS12 keystore generated by create-keystore.ps1 uses one password.
    $env:ANDROID_RELEASE_KEY_PASSWORD = $password
    Remove-Variable password

    Push-Location $root
    try {
        $task = if ($Bundle) { ":app:bundleRelease" } else { ":app:assembleRelease" }
        & $gradlew $task "-Prubberband=true" "-PsourceRevision=$sourceRevision" "--no-daemon"
        if ($LASTEXITCODE -ne 0) { throw "Android release build failed ($LASTEXITCODE)." }

        if ($Bundle) {
            $built = Join-Path $root "app\build\outputs\bundle\release\app-release.aab"
            $name = "BPM_Player-1.0.0-rc1-r3-arm64.aab"
        } else {
            $built = Join-Path $root "app\build\outputs\apk\release\app-release.apk"
            $name = "BPM_Player-1.0.0-rc1-r3-arm64.apk"
        }
        if (-not (Test-Path -LiteralPath $built)) {
            throw "Build succeeded but output file not found: $built"
        }

        $destination = Join-Path $root "dist"
        New-Item -ItemType Directory -Path $destination -Force | Out-Null
        $target = Join-Path $destination $name
        Copy-Item -LiteralPath $built -Destination $target -Force

        # Build a full native-inclusive source package from the SAME revision.
        & $sourceScript -OutputDirectory $destination

        Write-Host "Signed release: $target"
        Write-Host "Source revision embedded: $sourceRevision"
        Write-Host "Do NOT distribute before publishing the matching corresponding-source ZIP"
        Write-Host "and checking the third-party licence/Play Store compliance checklist."
        Write-Host "Play Protect may still prompt for a scan during sideloading."
    } finally {
        Pop-Location
    }
} finally {
    [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
    Remove-Item Env:ANDROID_RELEASE_KEYSTORE -ErrorAction SilentlyContinue
    Remove-Item Env:ANDROID_RELEASE_STORE_PASSWORD -ErrorAction SilentlyContinue
    Remove-Item Env:ANDROID_RELEASE_KEY_ALIAS -ErrorAction SilentlyContinue
    Remove-Item Env:ANDROID_RELEASE_KEY_PASSWORD -ErrorAction SilentlyContinue
}
